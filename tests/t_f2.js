const { JSDOM } = require('jsdom'); const fs = require('fs');
const html = fs.readFileSync('/home/claude/live_five.html', 'utf-8');
const dom = new JSDOM(html, { runScripts: 'dangerously', resources: 'usable', url: 'https://example.com/', pretendToBeVisual: true });
dom.window.matchMedia = () => ({ matches: false, addEventListener: () => {}, removeEventListener: () => {} });
dom.window.alert = () => { dom.window.__alerted = true; };
const errors = []; dom.window.addEventListener('error', e => errors.push(e.message));
let fails = 0; const check = (l, c) => { if (!c) fails++; console.log((c ? 'PASS ' : 'FAIL ') + l); };
const click = el => el.dispatchEvent(new dom.window.MouseEvent('click', { bubbles: true }));
setTimeout(async () => {
  const doc = dom.window.document; const ev = s => dom.window.eval(s);
  // helper: build entries from a map of offset-days-ago -> 'log' | 'sick' | 'rest' | 'sick+log'
  const build = (map) => ev(`entries = []; const m = ${JSON.stringify(map)}; Object.entries(m).forEach(([off, kind]) => {
      const d = new Date(); d.setDate(d.getDate() - Number(off)); const e = { date: (d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + String(d.getDate()).padStart(2, '0')) };
      if (kind.includes('log')) e.steps = '9000'; if (kind.includes('sick')) e.restDay = 'sick'; if (kind.includes('rest')) e.restDay = 'rest'; entries.push(e); });
      entries.sort((a,b)=>a.date.localeCompare(b.date));`);
  console.log('=== 1. current streak: a sick day pauses, never breaks ===');
  build({0:'log', 1:'log', 2:'log'}); check('baseline 3 days logged -> 3', ev('currentLoggingStreak()') === 3);
  build({0:'log', 1:'sick', 2:'log', 3:'log', 4:'log'});
  check('sick day in the middle: bridged, not counted -> 1 + 3 = 4', ev('currentLoggingStreak()') === 4);
  build({0:'log', 1:'', 2:'log', 3:'log', 4:'log'}); check('same pattern WITHOUT the flag still breaks (-> 1)', ev('currentLoggingStreak()') === 1);
  build({0:'log', 1:'rest', 2:'rest', 3:'log', 4:'log'}); check('two rest days in a row both bridge -> 1 + 2 = 3', ev('currentLoggingStreak()') === 3);
  build({0:'log', 1:'sick', 2:'', 3:'log', 4:'log'}); check('a real unflagged gap beyond the sick day still breaks -> 1', ev('currentLoggingStreak()') === 1);
  build({0:'log', 1:'sick+log', 2:'log'}); check('logging on a sick day still counts normally -> 3', ev('currentLoggingStreak()') === 3);
  build({0:'sick', 1:'log', 2:'log'}); check('today flagged sick, nothing logged yet: streak from yesterday intact -> 2', ev('currentLoggingStreak()') === 2);
  console.log('=== 2. longest streak (badges) follows the same rule ===');
  const pred = `(ds, e) => e && e.steps`;
  build({0:'log', 1:'log', 2:'sick', 3:'log', 4:'log', 5:'log'}); check('5 logged days with a sick day inside -> 5', ev(`longestStreak(${pred})`) === 5);
  build({0:'log', 1:'log', 2:'', 3:'log', 4:'log', 5:'log'}); check('without the flag the gap splits it -> 3', ev(`longestStreak(${pred})`) === 3);
  build({0:'log', 1:'sick', 2:'log'}); check('flagged day itself is never counted as a logged day -> 2', ev(`longestStreak(${pred})`) === 2);
  console.log('=== 3. setDayStatus saves + toggles ===');
  build({0:'log', 1:'log', 2:'log'});
  ev(`window.__calls = []; window.__setDocImpl = (ref, data, opts) => { window.__calls.push({ data, opts }); return Promise.resolve(); }; syncId = 'x';`);
  await ev(`setDayStatus(todayStr(), 'sick')`);
  check('local entry flagged', ev(`dayStatusFor(todayStr())`) === 'sick');
  const call = ev('window.__calls[0]');
  check('merge-written to Firestore with restDay', call && call.data.restDay === 'sick' && call.opts.merge === true);
  await ev(`setDayStatus(todayStr(), null)`);
  check('clearing removes the flag', ev(`dayStatusFor(todayStr())`) === null);
  ev(`window.__setDocImpl = () => Promise.reject(new Error('boom')); window.__alerted = false;`);
  await ev(`setDayStatus(todayStr(), 'rest')`);
  check('failed save rolls back to the previous status', ev(`dayStatusFor(todayStr())`) === null);
  check('and tells you', dom.window.__alerted === true);
  ev(`window.__setDocImpl = (r, d, o) => Promise.resolve();`);
  console.log('=== 4. Home streak card control ===');
  build({0:'log', 1:'log', 2:'log'}); ev('updateStats()');
  const box = doc.getElementById('scLoggingStreakRest');
  check('shows Sick / Rest pills when there is a streak to protect', box.querySelectorAll('[data-reststatus]').length === 2);
  click(box.querySelector('[data-reststatus="sick"]')); await new Promise(r => setTimeout(r, 30));
  check('tapping Sick flags today', ev(`dayStatusFor(todayStr())`) === 'sick');
  check('card now says streak is paused, with undo', /Sick/.test(box.textContent) && /paused/.test(box.textContent) && !!box.querySelector('[data-restundo]'));
  click(box.querySelector('[data-restundo]')); await new Promise(r => setTimeout(r, 30));
  check('undo clears it and the pills return', ev(`dayStatusFor(todayStr())`) === null && box.querySelectorAll('[data-reststatus]').length === 2);
  build({}); ev('updateStats()');
  check('no streak and no flag -> control stays out of the way', box.innerHTML === '');
  console.log('=== 5. Log tab chips, per selected date ===');
  build({0:'log'});
  const yd = ev(`(() => { const d = new Date(); d.setDate(d.getDate() - 1); return (d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + String(d.getDate()).padStart(2, '0')); })()`);
  ev(`document.getElementById('fDate').value = '${yd}'; document.getElementById('fDate').dispatchEvent(new Event('change'));`);
  click(doc.querySelector('#dayStatusRow [data-daystatus="rest"]')); await new Promise(r => setTimeout(r, 30));
  check('flags the SELECTED date (yesterday), not today', ev(`dayStatusFor('${yd}')`) === 'rest' && ev(`dayStatusFor(todayStr())`) === null);
  check('chip shows as active', doc.querySelector('#dayStatusRow [data-daystatus="rest"]').classList.contains('on'));
  ev(`document.getElementById('fDate').value = todayStr(); document.getElementById('fDate').dispatchEvent(new Event('change'));`);
  check('switching date updates the chips (today has none)', !doc.querySelector('#dayStatusRow .chip.on'));
  ev(`document.getElementById('fDate').value = '${yd}'; document.getElementById('fDate').dispatchEvent(new Event('change'));`);
  click(doc.querySelector('#dayStatusRow [data-daystatus="rest"]')); await new Promise(r => setTimeout(r, 30));
  check('tapping the active chip clears it', ev(`dayStatusFor('${yd}')`) === null);
  console.log('=== 6. workout nudge ===');
  build({0:'sick'}); check('sick day -> kind message, no "get back in" nag', /Sick day/.test(ev('workoutNudgeHtml()')) && !/get back in/.test(ev('workoutNudgeHtml()')));
  build({0:'rest'}); check('rest day -> rest message', /Rest day/.test(ev('workoutNudgeHtml()')));
  console.log('=== 7. heatmap tint ===');
  build({0:'log', 1:'sick', 2:'log'}); ev(`document.getElementById('foodDate').value = todayStr(); showView('history'); renderConsistencyHeatmap();`);
  const rects = [...doc.querySelectorAll('#consistencyHeatmap rect[data-date]')];
  const sickDate = ev(`(() => { const d = new Date(); d.setDate(d.getDate() - 1); return (d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + String(d.getDate()).padStart(2, '0')); })()`);
  const sickRect = rects.find(r => r.dataset.date === sickDate);
  check('sick day cell gets the lavender pause tint, not the empty gray', sickRect && sickRect.getAttribute('fill') === '#9B7BC4');
  console.log('=== 8. badges use the bridged streak ===');
  build({0:'log', 1:'log', 2:'sick', 3:'log', 4:'log', 5:'log'});
  check('Consistency data reflects the bridged run', ev(`computeBadgeData().loggingStreak`) === 5);
  console.log('=== Errors ==='); console.log(errors.length ? errors.join('\n') : '(none)');
  console.log(fails ? `\n${fails} FAILED` : '\nALL PASSED'); process.exit(0);
}, 2000); setTimeout(() => process.exit(1), 25000);
